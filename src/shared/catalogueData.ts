function buildProduct(seed: RawProductSeed): Product {
  const tier = seed.safetyTier ?? 'standard';
  const safety = safetyCopyForTier(tier);
  const pdfSources: PdfSourceRef[] = seed.sources.map((s) => ({
    section: s.section,
    sectionTitleHi: SECTION_META[s.section].sectionTitleHi,
    sectionTitleEn: SECTION_META[s.section].sectionTitleEn,
    page: SECTION_META[s.section].page,
    groupId: s.groupId,
    originalText: s.originalText,
  }));

  const variants: ProductVariant[] = (seed.variants ?? []).map((v) => ({
    ...v,
    priceText: 'Contact for Price',
    stockStatus: 'confirm_availability',
  }));

  const uniqueCategories = Array.from(new Set([seed.primaryCategory, ...seed.categories]));

  return {
    id: seed.id,
    slug: seed.slug,
    originalPdfName: seed.originalPdfName,
    nameHi: seed.nameHi,
    nameEn: seed.nameEn,
    alternativeNamesHi: seed.altHi ?? [],
    alternativeNamesEn: seed.altEn ?? [],
    searchAliases: Array.from(
      new Set([
        seed.nameHi,
        seed.nameEn,
        seed.originalPdfName,
        ...(seed.altHi ?? []),
        ...(seed.altEn ?? []),
        ...seed.aliases,
      ])
    ),
    primaryCategory: seed.primaryCategory,
    categories: uniqueCategories,
    pdfSources,
    variants,
    botanicalName: null,
    botanicalStatus: seed.botanicalStatus ?? 'pending',
    safetyTier: tier,
    regulatoryNote: seed.regulatoryNote ?? safety.reg,
    descriptionHi: seed.descriptionHi,
    descriptionEn: seed.descriptionEn,
    traditionalUsesHi: seed.traditionalUsesHi,
    traditionalUsesEn: seed.traditionalUsesEn,
    evidenceNoteHi: DEFAULT_EVIDENCE_HI,
    evidenceNoteEn: DEFAULT_EVIDENCE_EN,
    productForm: seed.productForm,
    images: [],
    packagingImages: [],
    packSizes: [],
    priceDisplay: 'Contact for Price',
    stockStatus: 'confirm_availability',
    safetyInfoHi: safety.hi,
    safetyInfoEn: safety.en,
    storageInfoHi: DEFAULT_STORAGE_HI,
    storageInfoEn: DEFAULT_STORAGE_EN,
    seoTitleHi: `${seed.nameHi} (${seed.nameEn}) — कन्हैया औषधि भंडार, आगरा`,
    seoTitleEn: `${seed.nameEn} (${seed.nameHi}) — Kanhaiya Aushadhi Bhandar, Agra`,
    metaDescriptionHi: `कन्हैया औषधि भंडार, खेरिया मोड़ चौराहा, आगरा की आधिकारिक सूची में शामिल ${seed.nameHi} (${seed.nameEn})। उपलब्धता, रूप एवं पैकेजिंग हेतु संपर्क करें।`,
    metaDescriptionEn: `${seed.nameEn} (${seed.nameHi}) listed in the official catalogue of Kanhaiya Aushadhi Bhandar, Kheria Mod Chauraha, Agra. Contact store for availability and packaging.`,
    featured: Boolean(seed.featured),
    publicationStatus: 'published',
    indexable: false,
    updatedAt: '2026-11-27T00:00:00.000Z',
  };
}

